% 定义传递函数的分子和分母多项式系数
K = 1; % 增益K，可根据需要修改
num = K * [4 1]; % 分子多项式系数，对应 4s + 1
den = conv([1 0 0], [1 6 2]); % 分母多项式系数，先处理 s^2，再与 s^2 + 6s + 2 卷积

% 创建传递函数对象
sys = tf(num, den);

% 绘制奈奎斯特图
nyquist(sys);
grid on; % 显示网格
title('奈奎斯特图 of G(s) = K(4s + 1)/(s^2(s^2 + 6s + 2))'); % 设置标题
xlabel('实轴'); % 设置x轴标签
ylabel('虚轴'); % 设置y轴标签